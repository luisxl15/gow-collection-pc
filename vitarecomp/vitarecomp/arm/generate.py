"""Write the C translation unit set for an analysed ARM program."""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

from .analysis import Program
from .emit import emit_function, fname

FUNCS_PER_FILE = 300


def generate(prog: Program, out: Path, trace: bool = False) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    funcs = sorted(prog.functions.values(), key=lambda f: f.key)
    hdr = ["/* Generated by vitarecomp. Do not edit. */", "#ifndef ARC_FUNCS_H", "#define ARC_FUNCS_H",
           '#include "arc.h"'] + [f"void {fname(f)}(arc_ctx *ctx);" for f in funcs] + ["#endif", ""]
    (out / "arc_funcs.h").write_text("\n".join(hdr))
    sources, errors = [], []
    for n in range(0, len(funcs), FUNCS_PER_FILE):
        body = ["/* Generated by vitarecomp. Do not edit. */", '#include "arc_funcs.h"', ""]
        for f in funcs[n:n + FUNCS_PER_FILE]:
            text, errs = emit_function(prog, f, trace)
            body.append(text + "\n")
            errors += errs
        name = f"arc_funcs_{n // FUNCS_PER_FILE:03d}.c"
        (out / name).write_text("\n".join(body))
        sources.append(name)
    table = ["/* Generated by vitarecomp. Do not edit. */", '#include "arc_funcs.h"',
             "const arc_func_entry arc_func_table[] = {"]
    table += [f'  {{{f.key:#010x}u, {fname(f)}, "{f.name}"}},' for f in funcs]
    table += ["};", f"const unsigned arc_func_count = {len(funcs)};", ""]
    segs = prog.img.segments
    img = ["/* Generated by vitarecomp. Do not edit. */", '#include "arc.h"']
    for k, s in enumerate(segs):
        data = s.data or b"\0"
        img.append(f"static const uint8_t seg{k}[{len(data)}] = {{")
        img += ["  " + ",".join(str(b) for b in data[j:j + 40]) + "," for j in range(0, len(data), 40)]
        img.append("};")
    img.append("const arc_segment arc_segments[] = {")
    img += [f"  {{{s.addr:#010x}u, {len(s.data)}u, {s.memsz}u, seg{k}}}," for k, s in enumerate(segs)]
    img += ["};", f"const unsigned arc_segment_count = {len(segs)};",
            f"const uint32_t arc_entry = {prog.img.entry:#010x}u;", ""]
    (out / "arc_table.c").write_text("\n".join(table))
    (out / "arc_image.c").write_text("\n".join(img))
    sources += ["arc_table.c", "arc_image.c"]
    names = Counter(i.name for f in funcs for i in f.insns.values())
    manifest = {
        "functions": len(funcs),
        "thumb_functions": sum(f.thumb for f in funcs),
        "instructions": sum(len(f.insns) for f in funcs),
        "untranslated": errors,
        "undecodable": {fname(f): [hex(a) for a in f.unknown] for f in funcs if f.unknown},
        "unresolved_indirect": {fname(f): [hex(a) for a in f.indirect_jumps] for f in funcs if f.indirect_jumps},
        "warnings": prog.warnings,
        "instruction_histogram": dict(names.most_common()),
        "sources": sources,
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest
