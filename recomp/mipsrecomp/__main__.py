"""CLI: python -m mipsrecomp <guest.elf> -o <outdir> [--trace] [--allow-unknown]"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections import Counter
from pathlib import Path

from . import elf as elfmod
from .analysis import AnalysisError, analyze
from .emitter import EmitError, Emitter, fname

FUNCS_PER_FILE = 200


def write_if_changed(path: Path, text: str) -> None:
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="mipsrecomp")
    ap.add_argument("elf", type=Path)
    ap.add_argument("-o", "--out", type=Path, required=True)
    ap.add_argument("--trace", action="store_true", help="emit function-entry trace hooks")
    ap.add_argument("--trace-insn", action="store_true",
                    help="log full CPU state before every instruction (lockstep debugging)")
    ap.add_argument("--allow-unknown", action="store_true",
                    help="emit runtime traps for undecodable words instead of failing")
    args = ap.parse_args(argv)

    data = args.elf.read_bytes()
    try:
        elf = elfmod.parse(data)
        if elf.machine != elfmod.Elf.EM_MIPS:
            raise elfmod.ElfError(f"e_machine={elf.machine}, expected MIPS (8)")
        if elf.flags & 0x200:  # EF_MIPS_FP64
            raise elfmod.ElfError("FP64 (FR=1) objects are not supported; the runtime models FR=0")
        prog = analyze(elf)
    except (elfmod.ElfError, AnalysisError) as e:
        print(f"mipsrecomp: error: {e}", file=sys.stderr)
        return 1

    if prog.unknown and not args.allow_unknown:
        for ins in prog.unknown[:20]:
            print(f"mipsrecomp: error: undecodable instruction {ins}", file=sys.stderr)
        print(f"mipsrecomp: {len(prog.unknown)} undecodable word(s); use --allow-unknown to "
              "emit runtime traps instead", file=sys.stderr)
        return 1

    out = args.out
    out.mkdir(parents=True, exist_ok=True)
    em = Emitter(prog, trace=args.trace, trace_insn=args.trace_insn)
    funcs = sorted(prog.functions.values(), key=lambda f: f.start)

    header = ["/* Generated by mipsrecomp. Do not edit. */", "#ifndef RC_FUNCS_H",
              "#define RC_FUNCS_H", '#include "recomp.h"']
    header += [f"void {fname(f)}(rc_ctx *ctx);" for f in funcs]
    header += ["#endif", ""]
    write_if_changed(out / "rc_funcs.h", "\n".join(header))

    files = []
    try:
        for n in range(0, len(funcs), FUNCS_PER_FILE):
            chunk = funcs[n:n + FUNCS_PER_FILE]
            body = ["/* Generated by mipsrecomp. Do not edit. */", '#include "rc_funcs.h"', ""]
            body += [em.function(f) + "\n" for f in chunk]
            name = f"rc_funcs_{n // FUNCS_PER_FILE:03d}.c"
            write_if_changed(out / name, "\n".join(body))
            files.append(name)
    except EmitError as e:
        print(f"mipsrecomp: error: {e}", file=sys.stderr)
        return 1

    table = ["/* Generated by mipsrecomp. Do not edit. */", '#include "rc_funcs.h"', "",
             "const rc_func_entry rc_func_table[] = {"]
    table += [f'    {{{f.start:#010x}u, {fname(f)}, "{f.name}"}},' for f in funcs]
    table += ["};", f"const unsigned rc_func_count = {len(funcs)};", ""]

    # Guest memory image: initialised bytes of every PT_LOAD segment.
    segs = [s for s in elf.segments if s.type == 1 and s.memsz]
    img = ["/* Generated by mipsrecomp. Do not edit. */", '#include "recomp.h"', ""]
    for k, s in enumerate(segs):
        raw = elf.data[s.offset:s.offset + s.filesz]
        rows = [", ".join(f"{b}" for b in raw[j:j + 32]) for j in range(0, len(raw), 32)]
        img.append(f"static const uint8_t seg{k}[{max(len(raw), 1)}] = {{")
        img += [f"    {r}," for r in rows] or ["    0"]
        img.append("};")
    img.append("const rc_segment rc_segments[] = {")
    img += [f"    {{{s.vaddr:#010x}u, {s.filesz}u, {s.memsz}u, seg{k}}}," for k, s in enumerate(segs)]
    img += ["};", f"const unsigned rc_segment_count = {len(segs)};",
            f"const uint32_t rc_entry = {elf.entry:#010x}u;", ""]
    write_if_changed(out / "rc_table.c", "\n".join(table))
    write_if_changed(out / "rc_image.c", "\n".join(img))
    files += ["rc_table.c", "rc_image.c"]

    ops = Counter(i.op for f in funcs for i in f.insns.values() if i.op)
    manifest = {
        "input": str(args.elf),
        "sha256": hashlib.sha256(data).hexdigest(),
        "entry": f"{elf.entry:#010x}",
        "functions": [{"name": f.name, "start": f"{f.start:#010x}",
                       "chunks": [[f"{s:#010x}", f"{e:#010x}"] for s, e in f.chunks],
                       "instructions": len(f.insns),
                       "indirect_jump": f.has_indirect_jump,
                       "jump_table_targets": len(f.jump_table_targets)} for f in funcs],
        "instruction_count": sum(len(f.insns) for f in funcs),
        "opcode_histogram": dict(ops.most_common()),
        "undecodable": [f"{i.addr:#010x}:{i.word:#010x}" for i in prog.unknown],
        "warnings": prog.warnings,
        "sources": files,
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"mipsrecomp: {len(funcs)} functions, {manifest['instruction_count']} instructions "
          f"-> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
